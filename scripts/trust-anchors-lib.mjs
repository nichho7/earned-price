// Writes verify/trust-anchors.js: the only things offline verify trusts besides the code and the
// math (T-029 security review C-1, H-1, H-2). Every field comes from a file the escrow itself is
// built or deployed from, so the verifier and the contract can't drift apart unnoticed:
//   review_model, prompt_version, request_pins  test-vectors/review-pins.json (= contract/src/pins.rs,
//                                               checked by cargo test; recomputed by npm test)
//   key_sha256                                  sha256(canonicalJson(packs/pack-N/answer-key.json)),
//                                               the exact K bytes the buyer commits to and reveals
//   signers                                     contract/tee-signers.json (the deploy-time allowlist;
//                                               the live list is the contract's signers() view)
// test/trust-anchors.test.js fails when the committed file differs from this output.
//   node scripts/trust-anchors.mjs        (rewrites verify/trust-anchors.js; run on purpose only)
// T-088: this is the library (tests and other scripts import it); `node scripts/trust-anchors.mjs` is the CLI and always
// runs main() (same lib/CLI split as fe4e769: no "am I the main module?" check, which skipped main() via a symlink).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { canonicalJson, sha256Hex } from "../grader/grade.js";
import { loadPack, readIndex } from "../packs/packs.js";

const ROOT = new URL("..", import.meta.url);
const readJson = (p) => JSON.parse(readFileSync(new URL(p, ROOT), "utf8"));
export const TRUST_FILE = fileURLToPath(new URL("verify/trust-anchors.js", ROOT));

export function buildTrustAnchors() {
  const pins = readJson("test-vectors/review-pins.json");
  const index = readIndex();
  const key_sha256 = {};
  for (const p of index) key_sha256[`pack-${p.id}`] = sha256Hex(canonicalJson(loadPack(p.id, index).key));
  const signers = readJson("contract/tee-signers.json").signers.map((s) => s.toLowerCase());
  for (const s of signers) if (!/^0x[0-9a-f]{40}$/.test(s)) throw new Error(`bad signer address in contract/tee-signers.json: ${s}`);
  return {
    review_model: pins.model,
    prompt_version: pins.prompt_version,
    request_pins: Object.fromEntries(pins.packs.map((p) => [p.pack_id, p.request_sha256])),
    key_sha256,
    signers,
  };
}

export function trustAnchorsSource(t = buildTrustAnchors()) {
  const map = (o) => `Object.freeze({\n${Object.entries(o).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n  })`;
  return `// GENERATED by scripts/trust-anchors.mjs: do not edit by hand. npm test fails if this file drifts
// from its sources (test-vectors/review-pins.json = contract/src/pins.rs, packs/*/answer-key.json,
// contract/tee-signers.json). Isomorphic: no imports, so the browser verify page loads it as is.
// signers is the escrow's deploy-time allowlist; the live list is the contract's signers() view.
export const TRUST = Object.freeze({
  review_model: ${JSON.stringify(t.review_model)},
  prompt_version: ${JSON.stringify(t.prompt_version)},
  request_pins: ${map(t.request_pins)},
  key_sha256: ${map(t.key_sha256)},
  signers: Object.freeze(${JSON.stringify(t.signers)}),
});
`;
}

/** The CLI: rewrites verify/trust-anchors.js. */
export function main() {
  writeFileSync(TRUST_FILE, trustAnchorsSource());
  console.log(`wrote ${TRUST_FILE}`);
}
